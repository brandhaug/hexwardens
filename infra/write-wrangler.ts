import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import {
	durableObjects,
	durableObjectMigrations,
	localDatabaseId,
	rateLimitBindings,
	stageResourceNames,
	workerCompatibility
} from './bindings.ts'

const names = stageResourceNames('prod')
const limits = rateLimitBindings('prod')
function rateLimit(spec: typeof limits.web) {
	return [
		{ name: spec.name, namespace_id: spec.namespaceId, simple: spec.simple }
	]
}
const defaults = {
	$schema: '../../node_modules/wrangler/config-schema.json',
	compatibility_date: workerCompatibility.date,
	compatibility_flags: workerCompatibility.flags
}
function database(migrationsDir: string) {
	return [
		{
			binding: 'DB',
			database_name: names.database,
			database_id: localDatabaseId,
			migrations_dir: migrationsDir
		}
	]
}
const configurations = {
	'apps/game-server/wrangler.jsonc': {
		...defaults,
		name: names.gameServer,
		main: 'src/index.ts',
		ratelimits: rateLimit(limits.game),
		durable_objects: {
			bindings: Object.entries(durableObjects).map(([name, class_name]) => ({
				name,
				class_name
			}))
		},
		migrations: durableObjectMigrations,
		observability: { enabled: true },
		vars: { ALLOWED_ORIGIN: 'http://localhost:3001' },
		d1_databases: database('../../packages/db/migrations')
	},
	'apps/web/wrangler.jsonc': {
		...defaults,
		name: names.web,
		main: 'src/server.ts',
		ratelimits: rateLimit(limits.web),
		observability: { enabled: true },
		d1_databases: database('../../packages/db/migrations')
	},
	'packages/db/wrangler.jsonc': {
		...defaults,
		name: 'hexwardens-db-migrations',
		d1_databases: database('./migrations')
	}
}
const check = process.argv.includes('--check')
for (const [path, config] of Object.entries(configurations)) {
	const target = fileURLToPath(new URL(`../${path}`, import.meta.url))
	const content = `// Generated by infra/write-wrangler.ts. Local development only.\n${JSON.stringify(config, null, '\t')}\n`
	if (check) {
		const committed: unknown = JSON.parse(
			readFileSync(target, 'utf8').replace(/^\/\/[^\n]*\n/, '')
		)
		if (JSON.stringify(committed) !== JSON.stringify(config)) {
			throw new Error(`Generated config drift: ${path}. Run infra:wrangler.`)
		}
	} else {
		writeFileSync(target, content)
	}
}
